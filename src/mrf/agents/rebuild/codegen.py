"""Deterministic rebuild for regression-type legacy models (the fallback when the LLM is unavailable or wrong).

A logistic / linear regression is fully described by its parameter estimates, so the Python scoring function can
be *transcribed* from the legacy export instead of written by an LLM: every coefficient is copied verbatim, the
categorical terms use the legacy reference coding (the reference level has no coefficient -> contributes 0).

The generated module follows the sandbox contract used by ``run_parity``::

    def score(input_csv: str) -> dict:   # {"scores": [float, ...]} in input row order
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any

SUPPORTED_LINKS = ("logit", "identity")


@dataclass
class ModelSpec:
    """What the legacy export says about the model."""

    link: str
    intercept: float
    numeric: dict[str, float] = field(default_factory=dict)  # column -> coefficient
    levels: dict[str, dict[str, float]] = field(default_factory=dict)  # column -> {level: coefficient}
    unmatched: list[str] = field(default_factory=list)  # terms that match no input column

    def summary(self) -> dict[str, Any]:
        return {
            "link": self.link,
            "n_numeric_terms": len(self.numeric),
            "n_categorical_terms": sum(len(v) for v in self.levels.values()),
            "categorical_columns": sorted(self.levels),
            "unmatched_terms": self.unmatched,
        }


def level_key(value: Any) -> str:
    """Canonical text of a category level: 3, 3.0 and '3' are the same level."""
    text = str(value).strip()
    try:
        number = float(text)
    except ValueError:
        return text
    return str(int(number)) if number == int(number) else text


def build_spec(coefficients: dict[str, float], columns: list[str], link: str = "logit") -> ModelSpec:
    """Match legacy terms to input columns: an exact column name is numeric, ``<column>_<level>`` is a level."""
    spec = ModelSpec(link=link, intercept=0.0)
    by_length = sorted(columns, key=len, reverse=True)  # longest prefix first: 'age_band' before 'age'
    for term, coef in coefficients.items():
        if term.lower() in {"intercept", "(intercept)", "const"}:
            spec.intercept = float(coef)
        elif term in columns:
            spec.numeric[term] = float(coef)
        else:
            column = next((c for c in by_length if term.startswith(c + "_") and len(term) > len(c) + 1), None)
            if column is None:
                spec.unmatched.append(term)
            else:
                spec.levels.setdefault(column, {})[level_key(term[len(column) + 1 :])] = float(coef)
    return spec


_TEMPLATE = '''"""Python rebuild of legacy model {model_name} (generated by the Model Risk Factory).

Scoring function transcribed from the legacy parameter estimates; link: {link}.
Categorical variables use reference coding: a level without a coefficient is the reference (contributes 0).
"""
import io

import numpy as np
import pandas as pd

LINK = {link!r}
INTERCEPT = {intercept!r}
NUMERIC = {numeric}
LEVELS = {levels}


def _level(value):
    text = str(value).strip()
    try:
        number = float(text)
    except ValueError:
        return text
    return str(int(number)) if number == int(number) else text


def linear_predictor(df):
    eta = np.full(len(df), INTERCEPT, dtype=float)
    for column, coefficient in NUMERIC.items():
        eta += coefficient * pd.to_numeric(df[column], errors="coerce").to_numpy(dtype=float)
    for column, coefficients in LEVELS.items():
        eta += df[column].map(_level).map(coefficients).fillna(0.0).to_numpy(dtype=float)
    return eta


def score(input_csv):
    df = pd.read_csv(io.StringIO(input_csv))
    eta = linear_predictor(df)
    values = 1.0 / (1.0 + np.exp(-eta)) if LINK == "logit" else eta
    return {{"scores": [float(v) for v in values]}}
'''


def render(spec: ModelSpec, model_name: str = "model") -> str:
    """Python source of the scoring module for a spec."""
    if spec.link not in SUPPORTED_LINKS:
        raise ValueError(f"unsupported link '{spec.link}'")
    return _TEMPLATE.format(
        model_name=model_name.replace('"', "'"),
        link=spec.link,
        intercept=spec.intercept,
        numeric=json.dumps(spec.numeric, indent=4),
        levels=json.dumps(spec.levels, indent=4),
    )
