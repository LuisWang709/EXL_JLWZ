#!/usr/bin/env python3
"""Generate six synthetic R/SAS validation packages and optionally verify the real local pipeline.

    uv run --extra data python scripts/generate_validation_models.py --verify

Only the verification LLM is mocked. Parsing, rebuild, sandbox parity, scoring and report RAG are real.
Reference scores are generated by Python from frozen coefficients, not exported from a native R/SAS engine.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import tempfile
import zipfile
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from mrf import validation as v
from mrf.config import REPO_ROOT, get_policy

CASES = (
    ("GREEN", "GINI_GE_040", 1.8),
    ("AMBER", "GINI_030_040", 0.65),
    ("RED", "GINI_LT_030", 0.15),
)
PACKAGE_FILES = ("manifest.json", "input_sample.csv", "legacy_scores.csv", "coefficients.json")


def scores(frame: pd.DataFrame, coefficients: dict[str, float]) -> np.ndarray:
    eta = coefficients["intercept"] + sum(frame[k].to_numpy() * value for k, value in coefficients.items()
                                         if k != "intercept")
    return 1 / (1 + np.exp(-eta))


def _sample(seed: int, coefficients: dict[str, float], offset: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    base = pd.DataFrame({"risk_driver": rng.normal(size=300), "utilisation": rng.uniform(size=300)})
    base["default_flag"] = rng.binomial(1, scores(base, coefficients))
    # Matched groups deliberately isolate performance from fairness in this synthetic calibration.
    frame = pd.concat([base.assign(age_band=group) for group in (1, 2, 3)], ignore_index=True)
    frame.insert(0, "id", np.arange(offset + 1, offset + len(frame) + 1))
    return frame


def _metrics(frame: pd.DataFrame, coefficients: dict[str, float]) -> dict[str, float]:
    prediction = scores(frame, coefficients)
    return {"auc": v.auc(frame.default_flag, prediction), "gini": v.gini(frame.default_flag, prediction),
            "hl_p_value": v.hosmer_lemeshow(frame.default_flag, prediction)["p_value"],
            "disparate_impact": v.fairness(frame.default_flag, prediction, frame.age_band)["disparate_impact"]}


def _performance(gini: float) -> str:
    policy = get_policy()["reporting"]
    return "GREEN" if gini >= policy["gini_green"] else "AMBER" if gini >= policy["gini_amber"] else "RED"


def calibrated_data(colour: str, slope: float) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, float], dict[str, Any]]:
    coefficients = {"intercept": -0.1, "risk_driver": slope, "utilisation": 0.2}
    policy = get_policy()
    for seed in range(101, 501):
        development = _sample(seed, coefficients, 0)
        validation = _sample(seed + 10_000, coefficients, 10_000)
        dev, val = _metrics(development, coefficients), _metrics(validation, coefficients)
        psi = v.psi(scores(development, coefficients), scores(validation, coefficients))
        if all(_performance(m["gini"]) == colour and m["hl_p_value"] >= policy["reporting"]["hl_p_value_amber"]
               and m["disparate_impact"] >= policy["reporting"]["disparate_impact_green"] for m in (dev, val)) and (
                   psi < policy["monitoring"]["psi_amber"]):
            return development, validation, coefficients, {"seed": seed, "development": dev, "validation": val,
                                                           "psi_score": psi}
    raise RuntimeError(f"could not calibrate {colour} with the current project thresholds")


def source(language: str, name: str, coefficients: dict[str, float]) -> str:
    intercept, slope, utilisation = (coefficients[k] for k in ("intercept", "risk_driver", "utilisation"))
    note = (
        f"{name}: simulated probability of default model.\n"
        "Owner: Synthetic Validation Tests. Target: default_flag, one means default.\n"
        "Use: local testing only; all records are synthetic and contain no customer information.\n"
        "Frozen production parameters are supplied in coefficients.json. Do not refit them for the parity test.\n"
        "The reference fit below is diagnostic; exported scores use the frozen formula.\n"
        "Limitations: no real portfolio evidence or independent native-engine reference scores.\n"
        "The age_band groups are matched replicas for controlled fairness testing, not independent customers.\n"
        "Governance: H1 documentation approval and independent H2 validation sign-off are required.\n"
        "Monitoring compares future batches with the registered healthy baseline.\n"
    )
    if language == "R":
        return "".join("# " + line + "\n" for line in note.splitlines()) + f'''
fit_reference <- function(development) {{
  glm(default_flag ~ risk_driver + utilisation,
      family = binomial(link = "logit"), data = development)
}}

score <- function(input) {{
  eta <- {intercept} + {slope} * input$risk_driver + {utilisation} * input$utilisation
  plogis(eta)
}}

input <- read.csv("input_sample.csv")
legacy <- data.frame(id = input$id, pd_legacy = score(input))
write.csv(legacy, "legacy_scores.csv", row.names = FALSE)
'''
    return "/*\n" + note + "*/\n" + f'''
proc import datafile="input_sample.csv" out=work.synthetic dbms=csv replace;
  guessingrows=max;
  getnames=yes;
run;

/* Diagnostic fit; the frozen exported model below remains authoritative. */
proc logistic data=work.synthetic;
  model default_flag(event='1') = risk_driver utilisation / link=logit;
run;

data work.legacy_scores;
  set work.synthetic;
  eta = {intercept} + {slope} * risk_driver + {utilisation} * utilisation;
  pd_legacy = 1 / (1 + exp(-eta));
  keep id pd_legacy;
run;

proc export data=work.legacy_scores outfile="legacy_scores.csv" dbms=csv replace;
run;
'''


def _json(path: Path, value: Any) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n",
                    encoding="utf-8", newline="\n")


def generate(root: Path) -> list[dict[str, Any]]:
    root.mkdir(parents=True, exist_ok=True)
    index = []
    for colour, band, slope in CASES:
        development, validation, coefficients, calibration = calibrated_data(colour, slope)
        for language in ("R", "SAS"):
            name = f"SIM_{language}_{colour}_{band}"
            folder = root / language / name
            upload = folder / "upload_together"
            upload.mkdir(parents=True, exist_ok=True)
            filename = name + (".R" if language == "R" else ".sas")
            (upload / filename).write_text(source(language, name, coefficients), encoding="utf-8", newline="\n")
            _json(upload / "coefficients.json", coefficients)
            _json(upload / "manifest.json", {
                "model_id": name, "name": name, "source_language": language, "algorithm": "logistic_regression",
                "target": "default_flag", "record_id_column": "id", "score_column": "pd_legacy", "link": "logit",
                "feature_columns": ["risk_driver", "utilisation"],
                "tolerance": get_policy()["parity"]["abs_tolerance"],
                "synthetic": True, "reference_score_origin": "Python formula using frozen synthetic coefficients",
            })
            validation.to_csv(upload / "input_sample.csv", index=False, float_format="%.12g", lineterminator="\n")
            pd.DataFrame({"id": validation.id, "pd_legacy": scores(validation, coefficients)}).to_csv(
                upload / "legacy_scores.csv", index=False, float_format="%.12g", lineterminator="\n",
            )
            development.to_csv(folder / "development.csv", index=False, float_format="%.12g", lineterminator="\n")
            validation.to_csv(folder / "validation.csv", index=False, float_format="%.12g", lineterminator="\n")
            item = {"name": name, "language": language, "path": f"{language}/{name}",
                    "source": f"upload_together/{filename}",
                    "expected_rag": colour.lower(), "calibration": calibration}
            _json(folder / "expected.json", item)
            index.append(item)
    _json(root / "index.json", {"synthetic": True, "models": index, "policy": {
        key: get_policy()[section][key] for section, key in (
            ("reporting", "gini_green"), ("reporting", "gini_amber"), ("reporting", "hl_p_value_amber"),
            ("reporting", "disparate_impact_green"), ("monitoring", "psi_amber"),
        )
    }})
    return index


async def verify(root: Path, runtime: Path, index: list[dict[str, Any]]) -> list[dict[str, Any]]:
    from mrf import llm, storage
    from mrf.config import get_settings
    from mrf.contracts.models import Dataset, Pipeline, Rebuild, Report, Review, Run
    from mrf.core import PipelineState
    from mrf.orchestrator.graph import Orchestrator
    from mrf.orchestrator.service import UploadedFile, create_pipeline
    from mrf.storage import Collections

    os.environ.update(MRF_ENV="local", MRF_LLM_PROVIDER="mock", MRF_STORAGE_BACKEND="memory",
                      MRF_TOOL_TRANSPORT="inprocess", MRF_DATA_DIR=str(runtime), MRF_BLOB_ACCOUNT_URL="",
                      MLFLOW_TRACKING_URI=f"sqlite:///{(runtime / 'mlflow.db').as_posix()}")
    get_settings.cache_clear()
    storage.set_repo(storage.MemoryRepository())
    storage.set_blobs(storage.LocalBlobStore(runtime / "blobs"))
    llm.set_llm(None)
    repo = storage.get_repo()
    results = []
    for item in index:
        folder = root / item.get("path", item["name"])
        files = [UploadedFile(path.name, path.read_bytes()) for path in sorted((folder / "upload_together").iterdir())]
        pipeline, model = await create_pipeline(
            model_name=item["name"], files=files, owner="Synthetic Validation Tests",
        )
        for role, filename in (("development", "development.csv"), ("validation", "validation.csv")):
            dataset = Dataset(dataset_id=f"{model.model_id}_{role}", name=f"{item['name']}_{role}",
                              uri=str((folder / filename).resolve()), role=role, model_id=model.model_id)
            await repo.put(Collections.DATASETS, dataset.dataset_id, dataset)
            pipeline.dataset_ids.append(dataset.dataset_id)
        await repo.put(Collections.PIPELINES, pipeline.pipeline_id, pipeline)
        orch = Orchestrator()
        first = await orch.start(pipeline.pipeline_id)
        if first.gate != "H1":
            raise RuntimeError(f"{item['name']} did not reach H1: {first}")
        review = await repo.get(Collections.REVIEWS, first.review_id, Review)
        review.status, review.decided_by = "approved", "synthetic-local-test"
        await repo.put(Collections.REVIEWS, review.review_id, review)
        outcome = await orch.resume(pipeline.pipeline_id, {"decision": "approve", "operator": "synthetic-local-test"})
        if outcome.state != PipelineState.AWAITING_SIGNOFF:
            raise RuntimeError(f"{item['name']} did not reach H2: {outcome}")
        pipeline = await repo.get(Collections.PIPELINES, pipeline.pipeline_id, Pipeline)
        rebuild = await repo.get(Collections.REBUILDS, pipeline.artifacts["rebuild_id"], Rebuild)
        report = await repo.get(Collections.REPORTS, pipeline.artifacts["validation_report_id"], Report)
        if not rebuild.parity or not rebuild.parity.passed or report.rag_status != item["expected_rag"]:
            raise RuntimeError(f"{item['name']} unexpected parity or RAG: {report.summary}")
        for kind in ("analysis", "validation"):
            view = await repo.get(Collections.REPORTS, pipeline.artifacts[f"{kind}_report_id"], Report)
            if view.artifact:
                html = (await storage.get_blobs().get_bytes(view.artifact.uri)).decode("utf-8")
                (folder / f"{kind}_report.html").write_text(
                    "\n".join(line.rstrip() for line in html.splitlines()) + "\n", encoding="utf-8", newline="\n",
                )
        runs = [await repo.get(Collections.RUNS, run_id, Run) for run_id in pipeline.artifacts["run_ids"]]
        result = {"name": item["name"], "actual_rag": report.rag_status, "dimensions": report.summary["statuses"],
                  "recommendation": report.summary["recommendation"], "n_parity_records": rebuild.parity.n_records,
                  "n_parity_mismatches": rebuild.parity.n_mismatches, "llm_provider": "mock",
                  "native_r_sas_reference_verified": False,
                  "runs": [{"dataset_role": run.metrics["dataset_role"], "metrics": run.metrics} for run in runs]}
        _json(folder / "verification.json", result)
        results.append(result)
        print(f"{item['name']}: {report.rag_status}; parity {rebuild.parity.n_mismatches} mismatches; H2 pending",
              flush=True)
    _json(root / "verification.json", results)
    return results


def bundle(root: Path, index: list[dict[str, Any]]) -> Path:
    target = root / "synthetic_R_SAS_validation_models.zip"
    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for item in index:
            for path in sorted((root / item.get("path", item["name"])).rglob("*")):
                if path.is_file():
                    archive.write(path, path.relative_to(root))
        for filename in ("README.md", "index.json", "verification.json"):
            if (root / filename).is_file():
                archive.write(root / filename, filename)
    return target


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "output" / "test_models")
    parser.add_argument("--verify", action="store_true", help="run the local pipeline to H2 with a mock LLM")
    args = parser.parse_args()
    root = args.out.resolve()
    if (root / "index.json").exists():
        parser.error("output already contains a generated suite; choose a new --out directory")
    index = generate(root)
    (root / "README.md").write_text((REPO_ROOT / "models" / "synthetic_validation" / "README.md").read_text(
        encoding="utf-8"), encoding="utf-8")
    if args.verify:
        parent = REPO_ROOT / ".tmp" / "validation-model-verification"
        parent.mkdir(parents=True, exist_ok=True)
        runtime = Path(tempfile.mkdtemp(prefix="run-", dir=parent))
        asyncio.run(verify(root, runtime, index))
    print(bundle(root, index))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
